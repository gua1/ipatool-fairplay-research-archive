#!/usr/bin/env python3
"""Generate the natural 26A428 SIDB-consumer-to-current-SINF CFG."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

import generate_macos26a428_bootstrap_cfg_go as cfg
import generate_macos_fairplay_go_oracle as generator
from raw_macho_db import RawMachODatabase, dyld_info_fixups


START = 0x10008A644
STOP = 0x100234CDC
SHARDS = 6


def write_sharded_source(path: Path, source: str) -> int:
    marker = "\nfunc rawSourceSINFEntryBlock"
    pieces = source.split(marker)
    if len(pieces) < 2:
        raise ValueError("generated current-SINF source has no block functions")
    path.write_text(pieces[0] + "\n")
    for old in path.parent.glob(path.stem + "_blocks_*.go"):
        old.unlink()
    functions = ["func rawSourceSINFEntryBlock" + piece for piece in pieces[1:]]
    chunk = math.ceil(len(functions) / SHARDS)
    header = (
        "//go:build fairplayrawsource && !fairplaysidb && !fairplayframe "
        "&& !fairplaystate && !fairplay26a428\n\n"
        "// Code generated by generate_macos26a428_sinf_entry_cfg_go.py; DO NOT EDIT.\n"
        "package main\n\n"
    )
    for index in range(SHARDS):
        selected = functions[index * chunk : (index + 1) * chunk]
        if not selected:
            continue
        shard = path.with_name(path.stem + f"_blocks_{index:02d}.go")
        shard.write_text(header + "\n".join(selected))
    return len(functions)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary", type=Path)
    parser.add_argument("--block-profile", type=Path, action="append", required=True)
    parser.add_argument("--block-trace", type=Path, action="append", required=True)
    parser.add_argument("--go-output", type=Path, required=True)
    args = parser.parse_args()
    if len(args.block_profile) != len(args.block_trace):
        parser.error("each block profile requires one matching block trace")

    binary_hash = hashlib.sha256(args.binary.read_bytes()).hexdigest()
    fixups, _names = dyld_info_fixups(args.binary)
    database = RawMachODatabase(args.binary, fixups=fixups)
    sizes: dict[int, int] = {}
    blocks: list[int] = []
    seen: set[int] = set()
    events = 0
    for profile_path, trace_path in zip(args.block_profile, args.block_trace):
        profile = json.loads(profile_path.read_text())
        trace = json.loads(trace_path.read_text())
        for document in (profile, trace):
            if document["binary_sha256"] != binary_hash:
                raise ValueError("current-SINF trace build mismatch")
        if int(trace["start_pc"], 16) != START or int(trace["stop"]["pc"], 16) != STOP:
            raise ValueError("current-SINF trace has the wrong boundary")
        for row in profile["block_counts"]:
            address, size = int(row["pc"], 16), int(row["size"])
            if address in sizes and sizes[address] != size:
                raise ValueError(f"conflicting block size at {address:#x}")
            sizes[address] = size
        raw_blocks = [int(value, 16) for value in trace["recent_pcs"]]
        events += len(raw_blocks)
        for address in raw_blocks:
            if (
                address == STOP
                or address >= cfg.EXTERNAL_BASE
                or address == cfg.NOOP_CALLBACK
                or address in seen
            ):
                continue
            seen.add(address)
            blocks.append(address)
    missing = [address for address in blocks if address not in sizes]
    if missing:
        raise ValueError(f"profiles lack {len(missing)} reached block sizes")

    generator.FAULT_SITES = {}
    original_start = cfg.START
    cfg.START = START
    try:
        source = cfg.generate_source(database, blocks, sizes, STOP)
    finally:
        cfg.START = original_start
    source = source.replace(
        "runRawSourceBootstrapCFG", "runRawSourceSINFEntryCFG"
    ).replace("rawSourceBootstrapBlock", "rawSourceSINFEntryBlock")
    args.go_output.parent.mkdir(parents=True, exist_ok=True)
    function_count = write_sharded_source(args.go_output, source)
    print(
        "fairplay_sinf_entry_cfg_generated=1 "
        f"blocks={len(blocks)} events={events} start={START:#x} "
        f"stop={STOP:#x} functions={function_count} shards={SHARDS} go={args.go_output}"
    )


if __name__ == "__main__":
    main()
