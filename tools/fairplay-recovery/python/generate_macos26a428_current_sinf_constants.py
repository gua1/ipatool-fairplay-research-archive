#!/usr/bin/env python3
"""Generate account-independent 26A428 current-SINF constants."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path
import pickle

from continue_fairplay_checkpoint_unicorn import checkpoint_memory_pages


def checkpoint_bytes(path: Path, address: int, size: int) -> bytes:
    with gzip.open(path, "rb") as stream:
        checkpoint = pickle.load(stream)
    pages = checkpoint_memory_pages(checkpoint)
    result = bytearray()
    while size:
        page_address = address & ~0xFFF
        page = pages[page_address]
        if not isinstance(page, bytes):
            expanded = bytearray(0x1000)
            for offset, value in page.items():
                expanded[offset] = value
            page = bytes(expanded)
        offset = address - page_address
        count = min(size, 0x1000 - offset)
        result.extend(page[offset : offset + count])
        address += count
        size -= count
    return bytes(result)


def go_array(name: str, value: bytes) -> str:
    rows = []
    for offset in range(0, len(value), 16):
        rows.append("\t" + ", ".join(f"0x{octet:02x}" for octet in value[offset : offset + 16]) + ",")
    return f"var {name} = [{len(value)}]byte{{\n" + "\n".join(rows) + "\n}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--enrollment-model", type=Path, action="append", required=True)
    parser.add_argument(
        "--material",
        action="append",
        required=True,
        metavar="CHECKPOINT=RECOVERY_JSON",
    )
    parser.add_argument("--go-output", type=Path, required=True)
    args = parser.parse_args()

    whitening_values = []
    table_values = []
    for path in args.enrollment_model:
        data = path.read_bytes()
        if len(data) != 4184 or data[:8] != b"FPSENR2\0":
            raise ValueError(f"unsupported enrollment model: {path}")
        whitening_values.append(data[72:88])
        table_values.append(data[88 : 88 + 4096])
    if len(set(whitening_values)) != 1 or len(set(table_values)) != 1:
        raise ValueError("current-SINF constants differ across enrollment models")

    masks = []
    for specification in args.material:
        checkpoint_text, separator, recovery_text = specification.partition("=")
        if not separator:
            raise ValueError("material requires CHECKPOINT=RECOVERY_JSON")
        checkpoint_path = Path(checkpoint_text)
        with gzip.open(checkpoint_path, "rb") as stream:
            checkpoint = pickle.load(stream)
        frame_pointer = int(checkpoint["registers"]["x29"])
        material = checkpoint_bytes(checkpoint_path, frame_pointer - 0x70, 16)
        key = bytes.fromhex(json.loads(Path(recovery_text).read_text())["key_hex"])
        if len(key) != 16:
            raise ValueError("current-SINF recovery is not AES-128")
        masks.append(bytes(left ^ right for left, right in zip(material, key)))
    if len(set(masks)) != 1:
        raise ValueError("current-SINF key projection differs across controls")

    mask = masks[0]
    whitening = whitening_values[0]
    tables = table_values[0]
    source = "\n".join(
        (
            "//go:build fairplayrawsource && !fairplaysidb && !fairplayframe && !fairplaystate && !fairplay26a428",
            "",
            "// Code generated by generate_macos26a428_current_sinf_constants.py; DO NOT EDIT.",
            "package main",
            "",
            f"// key-mask-sha256: {hashlib.sha256(mask).hexdigest()}",
            go_array("generatedCurrentSINFKeyMask", mask),
            f"// whitening-sha256: {hashlib.sha256(whitening).hexdigest()}",
            go_array("generatedCurrentSINFWhitening", whitening),
            f"// input-decode-sha256: {hashlib.sha256(tables).hexdigest()}",
            go_array("generatedCurrentSINFInputDecode", tables),
        )
    )
    args.go_output.parent.mkdir(parents=True, exist_ok=True)
    args.go_output.write_text(source)
    print(
        "fairplay_current_sinf_constants_generated=1 "
        f"controls={len(args.material)} models={len(args.enrollment_model)} "
        f"go={args.go_output}"
    )


if __name__ == "__main__":
    main()
