#!/usr/bin/env python3
"""Generate the public 26A428 state-slot input decoder."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import os
from pathlib import Path
import pickle


PAGE = 0x7000000FB000
SOURCE = 0x304
DESTINATION = 0x524


def load(path: Path) -> bytes:
    with gzip.open(path, "rb") as stream:
        checkpoint = pickle.load(stream)
    if checkpoint.get("binary_sha256") != "1e58d37e9602dd0ca5e24b14762063b6c310248b4d3a94272771d815e4ea1784":
        raise ValueError("checkpoint is not the checked 26A428 build")
    return checkpoint["memory_pages"][PAGE]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint_a", type=Path)
    parser.add_argument("checkpoint_b", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    page_a = load(args.checkpoint_a)
    page_b = load(args.checkpoint_b)
    masks = []
    for page, size in ((page_a, 224), (page_b, 192)):
        masks.append(
            bytes(
                left ^ right
                for left, right in zip(
                    page[SOURCE : SOURCE + size],
                    page[DESTINATION : DESTINATION + size],
                )
            )
        )
    mask = masks[0][:16]
    if masks[0] != mask * 14 or masks[1] != mask * 12:
        raise ValueError("state-slot input mask is not universal and 16-byte periodic")

    source = "\n".join(
        [
            "//go:build fairplaystate",
            "",
            "// Code generated by generate_macos26a428_state_input.py; DO NOT EDIT.",
            "package main",
            "",
            "var generatedStateInputMask = [16]byte{" + ",".join(
                f"0x{value:02x}" for value in mask
            ) + "}",
            "",
        ]
    )
    descriptor = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
    with os.fdopen(descriptor, "w") as stream:
        stream.write(source)
    print(
        "fairplay_state_input_generated=1 "
        f"mask_sha256={hashlib.sha256(mask).hexdigest()} output={args.output}"
    )


if __name__ == "__main__":
    main()
